// ========================================================================
// top_with_sram.sv - SYNTHESIS ONLY (Lab 2 Part 1, task 7)
// Same as top.sv, except imem and dmem are mapped to the OpenRAM
// SRAM_32x64_1rw macro instead of flip-flop arrays.
//
// This file has the following module implementations:
// 1. top    (interface unchanged)
// 2. mips   (5-stage pipeline, identical to top.sv)
// 3. dmem   (SRAM macro)
// 4. imem   (SRAM macro)
//
// Note: the SRAM registers its inputs on clk0, so reads are synchronous,
// unlike the combinational memories in top.sv. This version is therefore
// not cycle-equivalent to the simulated design; the handout only asks to
// synthesize it (no simulation), to compare area / timing with SRAM macros.
// =========================================================================
////////////////////////////////////////////////////////////////////////////
module top (
    input  logic        clk, reset,
    output logic [31:0] writedata, dataadr,
    output logic        memwrite
);
    logic [31:0] pc, instr, readdata;

    // instantiate processor and memories
    mips mips (clk, reset, pc, instr, memwrite, dataadr, writedata, readdata);
    imem imem (pc[7:2], instr);
    dmem dmem (clk, memwrite, dataadr, writedata, readdata);
endmodule


//////////////////////////////////////////////////////////////////////
// 5-stage pipelined MIPS Processor Module (same as top.sv)
//////////////////////////////////////////////////////////////////////
module mips (
    input  logic        clk, reset,
    output logic [31:0] pc,
    input  logic [31:0] instr,
    output logic        memwrite,           // driven by the datapath (MemWriteM)
    output logic [31:0] aluout, writedata,
    input  logic [31:0] readdata
);
    logic [31:0] instrD;
    logic memtoregD, memwriteD, branchD, alusrcD, regdstD, regwriteD, jumpD;
    logic [2:0] alucontrolD;

    // Controller decodes the Decode-stage instruction
    controller c (instrD[31:26], instrD[5:0],
                  memtoregD, memwriteD, branchD, alusrcD,
                  regdstD, regwriteD, jumpD, alucontrolD);

    datapath dp (.clk(clk), .reset(reset),
                 .alucontrolD(alucontrolD), .alusrcD(alusrcD), .regdstD(regdstD),
                 .branchD(branchD), .memwriteD(memwriteD),
                 .memtoregD(memtoregD), .regwriteD(regwriteD), .jumpD(jumpD),
                 .instr(instr), .readdata(readdata),
                 .pc(pc), .instrD(instrD),
                 .aluout(aluout), .writedata(writedata), .memwrite(memwrite));
endmodule


//////////////////////////////////////////////////////////////////////
// Data Memory Module
// - Uses the 32x64 SRAM macro generated by OpenRAM (from the provided
//   top_with_sram.v, converted to SystemVerilog)
//////////////////////////////////////////////////////////////////////
module dmem (
    input  logic        clk, we,
    input  logic [31:0] a, wd,
    output logic [31:0] rd
);
    // OpenRAM signals
    logic        csb0;      // chip select (active low)
    logic        web0;      // write enable (active low)
    logic [5:0]  addr0;     // 6-bit word address
    logic [31:0] din0;      // data input
    logic [31:0] dout0;     // data output

    assign csb0  = 1'b0;    // always enabled
    assign web0  = ~we;     // active-high we -> active-low web0
    assign addr0 = a[7:2];  // word-aligned address (64 words)
    assign din0  = wd;      // write data
    assign rd    = dout0;   // read data

    SRAM_32x64_1rw dmem_ram (
        .clk0 (clk),
        .csb0 (csb0),
        .web0 (web0),
        .addr0(addr0),
        .din0 (din0),
        .dout0(dout0)
    );
endmodule


//////////////////////////////////////////////////////////////////////
// Instruction Memory Module
// - Uses the 32x64 SRAM macro generated by OpenRAM (read-only use),
//   connected exactly as in the provided top_with_sram.v
//////////////////////////////////////////////////////////////////////
module imem (
    input  logic [5:0]  a,
    output logic [31:0] rd
);
    // OpenRAM interface signals
    logic        clk0;      // clock
    logic        csb0;      // chip select (active low)
    logic        web0;      // write enable (active low)
    logic [5:0]  addr0;     // 6-bit word address
    logic [31:0] din0;      // data input
    logic [31:0] dout0;     // data output

    assign clk0  = 1'b0;    // as provided: no clock for read-only use
    assign csb0  = 1'b0;    // always enabled
    assign web0  = 1'b1;    // always read (never write)
    assign addr0 = a;       // address from the processor
    assign din0  = 32'b0;   // no write data
    assign rd    = dout0;   // read data

    SRAM_32x64_1rw imem_ram (
        .clk0 (clk0),
        .csb0 (csb0),
        .web0 (web0),
        .addr0(addr0),
        .din0 (din0),
        .dout0(dout0)
    );
endmodule
